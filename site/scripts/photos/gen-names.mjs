// Writes src/lib/photo-names.gen.ts from the files in src/assets, so a photo
// name used in a page is checked by TypeScript. Runs before dev and build;
// a unit test fails if the generated list is stale.
import fs from "node:fs";

const names = fs
  .readdirSync("src/assets")
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .map((f) => f.replace(/\.(jpe?g|png|webp)$/i, ""))
  .sort();
const body = `// Generated by scripts/photos/gen-names.mjs from src/assets. Do not edit.
export const PHOTO_NAMES = [
${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
] as const;

export type PhotoName = (typeof PHOTO_NAMES)[number];
`;
const out = "src/lib/photo-names.gen.ts";
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);
